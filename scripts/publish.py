#!/usr/bin/env python3
"""Strict publish pipeline: auto-detect → test → lint → validate → consistency → bump → commit → push.

Auto-detects plugin name, version, marketplace, git root, and plugin root.
Handles subfolder plugins where git root != plugin root.

**NO SKIP POLICY (enforced):**
Every validation step (tests, lint, CPV --strict validate, version consistency)
MUST pass with zero errors before the version bump, commit, and push are
allowed. There are NO flags, environment variables, or configuration options
to bypass any validation step. If a step fails, the pipeline exits with the
failing step's exit code and no git state is changed.

This is a deliberate design choice. Do NOT add `--skip-*` flags, `FORCE=1`
overrides, or any other escape hatch — validation skipping caused a 2.5.1
release to ship without CPV strict signoff in the past. If a validation step
is wrong for the current release, fix the validator or fix the code, do not
bypass the check.

Usage:
  uv run python scripts/publish.py --patch            # bump patch and publish
  uv run python scripts/publish.py --minor            # bump minor and publish
  uv run python scripts/publish.py --major            # bump major and publish
  uv run python scripts/publish.py --patch --dry-run  # run every validation
                                                      # step then stop before
                                                      # bump/commit/push
  uv run python scripts/publish.py --gate             # read-only pre-push gate:
                                                      # every validation step,
                                                      # no bump/commit/tag/push
  uv run python scripts/publish.py --print-gates      # print the numbered
                                                      # pipeline stage list and
                                                      # exit 0 (no side effects)

Gate mode (--gate):
  Runs Steps 1-7.5 only — bypass guard, clean-tree check, language-native tests,
  language-native lint, CPV `--strict` plugin validation, secret scan,
  fork-parity probe, CI-parity preflight, version consistency, and the
  git-cliff availability precheck — then returns. It mutates no git state and
  takes no bump type, so it is safe to call from a git hook.
  NOTE (TRDD-D6P88CM1): NO runner invokes --gate automatically in this repo.
  The installed hook is `.githooks/pre-push` (`core.hooksPath=.githooks`), a
  process-ancestry check that refuses any push not descended from this script —
  strictly stricter than gating. `git-hooks/pre-push`, the CPV-canonical
  reference hook that calls --gate, is NOT installed here (declared divergence,
  plugin.json `cpv.pipeline.intentional_divergence`). Gate mode is NOT a
  bypass: it is a strict SUBSET of the release pipeline's checks, running the
  same functions with the same fail-fast semantics, and it deliberately cannot
  reach the bump/commit/tag/push stages at all.

Exit codes:
    0 - Success (every step passed with 0 errors)
    1 - Any step failed (fail-fast, no partial state)
"""

