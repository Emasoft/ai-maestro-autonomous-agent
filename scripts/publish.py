def update_pyproject_toml(plugin_root: Path, new_version: str) -> tuple[bool, str]:
    """Update version field in pyproject.toml."""
    path = plugin_root / "pyproject.toml"
    if not path.exists():
        return True, "pyproject.toml not found (skipped)"
    try:
        content = path.read_text(encoding="utf-8")
        pattern = r'^(version\s*=\s*["\'])(\d+\.\d+\.\d+)(["\'])$'
        old_version = None

        def _replace(m: re.Match[str]) -> str:
            nonlocal old_version
            old_version = m.group(2)
            return f"{m.group(1)}{new_version}{m.group(3)}"

        new_content, count = re.subn(pattern, _replace, content, flags=re.MULTILINE)
        if count == 0:
            return True, "pyproject.toml has no version field (skipped)"
        path.write_text(new_content, encoding="utf-8")
        return True, f"pyproject.toml: {old_version} -> {new_version}"
    except Exception as e:
        return False, f"pyproject.toml error: {e}"


def update_python_versions(plugin_root: Path, new_version: str) -> list[tuple[bool, str]]:
    """Update __version__ = 'X.Y.Z' in all Python files."""
    gi = _get_gi(plugin_root)
    results: list[tuple[bool, str]] = []

    # Use gitignore filter if available, else walk manually
    if gi is not None:
        py_files = list(gi.rglob("*.py"))
    else:
        py_files = [
            p for p in plugin_root.rglob("*.py")
            if not any(part.startswith(".") or part in ("node_modules", "__pycache__", "dist", "build", ".git")
                       for part in p.relative_to(plugin_root).parts)
        ]

    for py_file in py_files:
        try:
            content = py_file.read_text(encoding="utf-8")
            pattern = r'^(__version__\s*=\s*["\'])(\d+\.\d+\.\d+)(["\'])$'
            old_v = None

            def _replace(m: re.Match[str]) -> str:
                nonlocal old_v
                old_v = m.group(2)
                return f"{m.group(1)}{new_version}{m.group(3)}"

            new_content, count = re.subn(pattern, _replace, content, flags=re.MULTILINE)
            if count > 0:
                py_file.write_text(new_content, encoding="utf-8")
                rel = py_file.relative_to(plugin_root)
                results.append((True, f"{rel}: {old_v} -> {new_version}"))
        except Exception as e:
            rel = py_file.relative_to(plugin_root)
            results.append((False, f"{rel}: {e}"))
    return results


def update_readme_version(plugin_root: Path, new_version: str) -> tuple[bool, str]:
    """Update the `**Version**: X.Y.Z` line in README.md (if present).

    Anchored on the literal `**Version**:` label so it never touches an
    unrelated version-like token elsewhere in the prose.
    """
    path = plugin_root / "README.md"
    if not path.exists():
        return True, "README.md not found (skipped)"
    try:
        content = path.read_text(encoding="utf-8")
        # `[^\S\n]*$` = trailing horizontal whitespace only — NOT `\s*$`, which is
        # greedy across newlines and would swallow the blank line after the badge
        # (collapsing "**Version**: X\n\n## Overview" into "...X\n## Overview").
        pattern = r'^(\*\*Version\*\*:\s*)(\d+\.\d+\.\d+)[^\S\n]*$'
        old_v = None

        def _replace(m: re.Match[str]) -> str:
            nonlocal old_v
            old_v = m.group(2)
            return f"{m.group(1)}{new_version}"

        new_content, count = re.subn(pattern, _replace, content, flags=re.MULTILINE)
        if count == 0:
            return True, "README.md has no **Version** line (skipped)"
        path.write_text(new_content, encoding="utf-8")
        return True, f"README.md: {old_v} -> {new_version}"
    except Exception as e:
        return False, f"README.md error: {e}"


def update_persona_versions(plugin_root: Path, new_version: str) -> list[tuple[bool, str]]:
    """Update the `**Plugin**: <name> vX.Y.Z` line in every agents/*.md persona.

    Anchored on the literal `**Plugin**:` label + plugin name, so example
    text such as "expedite the v2.0 release" is never rewritten.
    """
    agents_dir = plugin_root / "agents"
    results: list[tuple[bool, str]] = []
    if not agents_dir.is_dir():
        return results
    pattern = r'(\*\*Plugin\*\*:\s*\S+\s+v)(\d+\.\d+\.\d+)'
    for md in sorted(agents_dir.rglob("*.md")):
        try:
            content = md.read_text(encoding="utf-8")
            old_v = None

            def _replace(m: re.Match[str]) -> str:
                nonlocal old_v
                old_v = m.group(2)
                return f"{m.group(1)}{new_version}"

            new_content, count = re.subn(pattern, _replace, content)
            if count > 0:
                md.write_text(new_content, encoding="utf-8")
                rel = md.relative_to(plugin_root)
                results.append((True, f"{rel}: {old_v} -> {new_version}"))
        except Exception as e:
            rel = md.relative_to(plugin_root)
            results.append((False, f"{rel}: {e}"))
    return results


# ── Version consistency check ────────────────────────────────────────────────


def check_version_consistency(plugin_root: Path) -> tuple[bool, str]:
    """Check all version sources match. Returns (ok, message)."""
    versions: dict[str, str] = {}

    pj = plugin_root / ".claude-plugin" / "plugin.json"
    if pj.exists():
        try:
            v = json.loads(pj.read_text(encoding="utf-8")).get("version")
            if isinstance(v, str):
                versions["plugin.json"] = v
        except Exception:
            pass

    pp = plugin_root / "pyproject.toml"
    if pp.exists():
        try:
            m = re.search(r'^version\s*=\s*["\']([^"\']+)["\']', pp.read_text(encoding="utf-8"), re.MULTILINE)
            if m:
                versions["pyproject.toml"] = m.group(1)
        except Exception:
            pass

    gi = _get_gi(plugin_root)
    py_files = list(gi.rglob("*.py")) if gi else [
        p for p in plugin_root.rglob("*.py")
        if not any(part.startswith(".") or part in ("node_modules", "__pycache__", "dist", "build", ".git")
                   for part in p.relative_to(plugin_root).parts)
    ]
    for py_file in py_files:
        try:
            content = py_file.read_text(encoding="utf-8")
            m = re.search(r'^__version__\s*=\s*["\']([^"\']+)["\']', content, re.MULTILINE)
            if m:
                rel = str(py_file.relative_to(plugin_root))
                versions[rel] = m.group(1)
        except Exception:
            pass

    # README.md "**Version**: X.Y.Z" display string (kept in sync by the live
    # Step-9 bumper language_bump_version(); PRRD S4.2)
    readme = plugin_root / "README.md"
    if readme.exists():
        try:
            m = re.search(
                r'^\*\*Version\*\*:\s*(\d+\.\d+\.\d+)[^\S\n]*$',
                readme.read_text(encoding="utf-8"),
                re.MULTILINE,
            )
            if m:
                versions["README.md"] = m.group(1)
        except Exception:
            pass

    # agents/*.md persona "**Plugin**: <name> vX.Y.Z" display string
    agents_dir = plugin_root / "agents"
    if agents_dir.is_dir():
        for md in sorted(agents_dir.rglob("*.md")):
            try:
                m = re.search(
                    r'\*\*Plugin\*\*:\s*\S+\s+v(\d+\.\d+\.\d+)',
                    md.read_text(encoding="utf-8"),
                )
                if m:
                    versions[str(md.relative_to(plugin_root))] = m.group(1)
            except Exception:
                pass

    if not versions:
        return True, "No version sources found"

    unique = set(versions.values())
    if len(unique) == 1:
        return True, f"All {len(versions)} sources consistent: {next(iter(unique))}"

    lines = ["Version mismatch detected:"]
    for src, ver in sorted(versions.items()):
        lines.append(f"  {src}: {ver}")
    return False, "\n".join(lines)


