# ── DEPENDENCY-RESOLUTION TAG (added by `cpv standardize --fix`, CPV issue #165) ──
# Since Claude Code 2.1.110 a version-constrained dependency on this plugin
# ({"name": "<this-plugin>", "version": ">=1.2"}) is resolved by listing THIS repo's
# tags, keeping ONLY those starting with "<this-plugin>--v", and fetching the highest
# one satisfying the range. The plain vX.Y.Z tag is IGNORED by that resolver.
#
# So without the tag below, releases of this plugin are UN-DEPENDABLE: every dependent
# fails to install with `no-matching-tag` and is DISABLED. The breakage is invisible
# from the depending side (an already-installed dependent keeps working), which is how
# it stayed hidden for months in the wild — do NOT remove this stage because "nothing
# seems to need it". NOTE the separator is a DOUBLE hyphen (`--v`); the single-hyphen
# `-v` form seen on some ecosystem tags matches the resolver's prefix filter and is
# therefore silently useless.


def _cpv_dependency_tag_name(root: Path, new_ver: str) -> str | None:
    """The `{plugin-name}--v{version}` tag Claude Code resolves dependencies against.

    The name is read from the MANIFEST, never from the directory name, so renaming
    the checkout (or the plugin) cannot silently desync the tag from the plugin it
    names. Returns None when the name is unreadable — the caller then WARNS loudly
    rather than inventing a name, because a SILENT skip is exactly how this defect
    survived unnoticed across many releases.
    """
    manifest = root / ".claude-plugin" / "plugin.json"
    if not manifest.is_file():
        return None
    try:
        name = json.loads(manifest.read_text(encoding="utf-8")).get("name")
    except (json.JSONDecodeError, OSError):
        return None
    return f"{name}--v{new_ver}" if name else None


def _cpv_dependency_push_refs(root: Path, new_ver: str) -> list[str]:
    """Create the dependency-resolution tag locally and return it as a push-ref list.

    Idempotent: an existing tag is left alone. Returns [] when the tag cannot be
    built, so the release still pushes rather than crashing the pipeline.

    Its result is pushed by the SINGLE `git push --atomic` in Step 13, together with
    the branch and the release tag — a release can never ship with one ref and not
    the other. (Before the push was made atomic this guarantee held only between the
    two TAGS; the branch went out in an earlier, separate push that could succeed
    while the tag push failed.)
    """
    dep_tag = _cpv_dependency_tag_name(root, new_ver)
    if dep_tag is None:
        print(
            "  WARNING: cannot read the plugin name from .claude-plugin/plugin.json "
            "- SKIPPING the dependency tag. Plugins depending on this one will fail "
            "to resolve this release with `no-matching-tag`."
        )
        return []
    probe = subprocess.run(
        ["git", "rev-parse", "--verify", f"refs/tags/{dep_tag}"],
        capture_output=True,
        text=True,
        cwd=str(root),
        check=False,
        timeout=10,
    )
    if probe.returncode != 0:
        subprocess.run(
            ["git", "tag", "-a", dep_tag, "-m", dep_tag.replace("--v", " ")],
            cwd=str(root),
            check=True,
            timeout=10,
        )
        print(f"  Dependency tag {dep_tag} created.")
    return [dep_tag]


# ── Interrupted-publish recovery helpers ──────────────────────────────────────
# A publish is four irreversible acts: bump files, commit, tag, push. Only the
# push is atomic (Step 13); the first three are already durable on disk by the
# time it runs. So when the push fails — transient network drop, a rejected ref,
# a GitHub 503 — the working copy is left AT the new version, committed and
# tagged, while origin is still one release behind.
#
# Re-running publish.py then read the LOCAL version as its bump baseline and
# produced N+2: the tagged-but-never-pushed N+1 was skipped forever, silently,
# and nothing resolves that version for any dependent plugin. This is not
# hypothetical — it is the failure CPV's own pipeline hit shipping v2.64.0.
#
# The fix is to make the baseline ORIGIN, not the working copy, and to make each
# already-completed act a no-op on re-run. Every helper below is read-only and
# fails CLOSED (returns None / False) so a git error can never be mistaken for
# "already done" — the worst case is that the pre-existing behaviour resumes.


def _git_capture(root: Path, args: list[str]) -> str | None:
    """Run a read-only git command; return stripped stdout, or None if it failed."""
    proc = subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        cwd=str(root),
        check=False,
        timeout=10,
    )
    return proc.stdout.strip() if proc.returncode == 0 else None


def _refresh_remote_ref(root: Path, branch: str) -> None:
    """Best-effort refresh of `origin/<branch>` before it is used as a release baseline.

    `_read_remote_version` resolves `origin/<branch>`, which is a LOCAL
    remote-tracking ref — only as fresh as the last fetch. In a long-lived clone
    that is routinely WEEKS stale (this repo's was 36 days old when the guard was
    added), and a stale baseline defeats the resume logic in BOTH directions:

      * stale-behind -> the guard sees the old version, decides "no divergence",
        and bumps onto a version another machine already published. The atomic
        push then fails at the very END, leaving the bumped+committed+tagged
        working copy this guard exists to prevent.
      * stale by more than one bump -> the "neither origin's version nor a bump
        of it" branch refuses a perfectly legitimate publish.

    Deliberately NON-FATAL and read-only: it updates tracking refs only, never the
    working tree, and a failure (offline, no remote, auth prompt) simply leaves the
    ref as-is — `_read_remote_version` then returns the stale-or-None value and the
    pre-existing behaviour resumes. Fetching is not a push; nothing is published here.
    """
    _git_capture(root, ["fetch", "--quiet", "origin", branch])


def _read_remote_version(root: Path, branch: str) -> str | None:
    """Read `.claude-plugin/plugin.json`'s version as it exists on origin/<branch>.

    Call `_refresh_remote_ref` first: this resolves the LOCAL tracking ref, which is
    only as current as the last fetch.

    Returns None when origin has no such ref or blob (first publish, offline,
    shallow clone) — the caller then falls back to the local value, i.e. exactly
    the behaviour that predates this guard.
    """
    blob = _git_capture(root, ["show", f"origin/{branch}:.claude-plugin/plugin.json"])
    if blob is None:
        return None
    try:
        version = json.loads(blob).get("version")
    except (json.JSONDecodeError, AttributeError):
        return None
    return version if isinstance(version, str) and parse_semver(version) else None


def _git_porcelain_clean(root: Path) -> bool:
    """True iff the working tree has no changes. A failed git call reads as NOT clean."""
    return _git_capture(root, ["status", "--porcelain"]) == ""


def _head_commit_message(root: Path) -> str:
    """HEAD's subject line, or '' when it cannot be read (never matches a release subject)."""
    return _git_capture(root, ["log", "-1", "--pretty=%s"]) or ""


def _local_tag_exists(root: Path, tag: str) -> bool:
    """True iff `tag` already exists locally (the mark of an interrupted run's tag step)."""
    return _git_capture(root, ["rev-parse", "--verify", f"refs/tags/{tag}"]) is not None


